"""Generates notification layouts (res/layout/notif_*.xml), stat icon and launcher icon from the skin JSON/PNG."""
import json, os
from PIL import Image
R = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main'); A = R + '/assets/skins'
j = json.load(open(A + '/strip.json'))
os.makedirs(R + '/res/layout', exist_ok=True); os.makedirs(R + '/res/drawable', exist_ok=True); os.makedirs(R + '/res/mipmap-xxxhdpi', exist_ok=True)
def layout(name, hdp):
    k = hdp / j['h']; wdp = j['w'] * k
    btn = ''.join(f'''
  <ImageButton android:id="@+id/b_{b['id']}" android:layout_width="{2*b['r']*k:.1f}dp" android:layout_height="{2*b['r']*k:.1f}dp" android:layout_marginLeft="{(b['cx']-b['r'])*k:.1f}dp" android:layout_marginTop="{(b['cy']-b['r'])*k:.1f}dp" android:padding="0dp" android:background="@android:color/transparent" android:contentDescription="{b['id']}"/>''' for b in j['buttons'])
    open(f'{R}/res/layout/{name}.xml', 'w').write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen_layout.py from skins/strip.json - do not edit -->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android" android:layout_width="match_parent" android:layout_height="{hdp:.0f}dp">
 <FrameLayout android:layout_width="{wdp:.1f}dp" android:layout_height="{hdp:.0f}dp" android:layout_gravity="center_horizontal">
  <ImageView android:id="@+id/art" android:layout_width="match_parent" android:layout_height="match_parent" android:scaleType="fitXY"/>{btn}
 </FrameLayout>
</FrameLayout>
''')
layout('notif_big', 120); layout('notif_small', 64)
open(R + '/res/drawable/ic_stat.xml', 'w').write('''<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24"><path android:fillColor="#FFFFFF" android:pathData="M8,5v14l11,-7z"/></vector>
''')
h = Image.open(A + '/head.png'); bb = h.getbbox(); sq = max(bb[2] - bb[0], bb[3] - bb[1]) + 80
ic = Image.new('RGBA', (sq, sq), (16, 20, 28, 255)); ic.alpha_composite(h.crop(bb), ((sq - (bb[2] - bb[0])) // 2, (sq - (bb[3] - bb[1])) // 2))
ic.resize((192, 192), Image.LANCZOS).save(R + '/res/mipmap-xxxhdpi/ic_launcher.png')
print('layouts ok')
